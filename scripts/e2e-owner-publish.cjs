const { chromium } = require('playwright');
const { randomUUID } = require('crypto');
let browser;
(async () => {
  const web = process.env.STAYHUB_WEB_URL || 'http://localhost:5173';
  browser = await chromium.launch({ ...(process.env.STAYHUB_BROWSER_PATH ? { executablePath: process.env.STAYHUB_BROWSER_PATH } : { channel: 'chrome' }), headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const email = `owner-${randomUUID()}@stayhub.test`, password = `Test-${randomUUID()}`;
  const title = `Casa Prueba ${Date.now()}`;
  await page.goto(`${web}/register`);
  await page.locator('#register-name').fill('Anfitrión Prueba');
  await page.locator('#register-email').fill(email);
  await page.locator('#register-role').selectOption('OWNER');
  await page.locator('#register-password').fill(password);
  await page.locator('#register-confirm').fill(password);
  await page.locator('form button[type=submit]').click();
  await page.waitForURL('**/login*', { timeout: 30000 });
  await page.locator('#email').fill(email); await page.locator('#password').fill(password);
  await page.locator('form button[type=submit]').click();
  await page.waitForURL(url => !url.pathname.startsWith('/login'), { timeout: 30000 });
  await page.goto(`${web}/host/new`);
  await page.getByLabel('Tipo de alojamiento').selectOption('HOUSE');
  await page.getByLabel('Nombre', { exact: true }).fill(title);
  await page.getByLabel('Descripción').fill('Alojamiento sintético de prueba local.');
  await page.getByLabel('Dirección', { exact: true }).fill('Calle de prueba 123');
  await page.getByLabel('Ciudad', { exact: true }).fill('Bogotá');
  await page.getByLabel('Región o estado').fill('Cundinamarca');
  await page.getByLabel('País (código ISO de 2 letras)').fill('CO');
  await page.getByLabel('Latitud (opcional)').fill('4.7110');
  await page.getByLabel('Longitud (opcional)').fill('-74.0721');
  await page.getByLabel('Nombre de la habitación').fill('Habitación de prueba');
  await page.getByLabel('Capacidad', { exact: true }).fill('2');
  await page.getByLabel('Precio por noche').fill('120000');
  await page.getByLabel('Moneda', { exact: true }).selectOption('COP');
  await page.getByLabel('Agregar fotos').setInputFiles({ name: 'foto.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64') });
  await page.getByRole('button', { name: 'Publicar propiedad' }).click();
  await page.waitForURL('**/property/*', { timeout: 30000 });
  const propertyId = new URL(page.url()).pathname.split('/').pop();
  await page.getByRole('heading', { name: title }).waitFor({ timeout: 30000 });
  const detailResponse = await page.request.get(`${web}/api/v1/properties/${propertyId}`);
  if (!detailResponse.ok()) throw new Error(`Detalle respondió ${detailResponse.status()}`);
  const detail = await detailResponse.json();
  if (detail.location?.latitude !== 4.711 || detail.location?.longitude !== -74.0721) throw new Error('Las coordenadas no persistieron en el detalle.');
  await page.locator('iframe[title*="mapa" i]').waitFor({ timeout: 30000 });
  for (let i = 0; i < 20; i++) {
    const response = await page.request.get(`${web}/api/v1/search?location=Bogot%C3%A1&pageSize=100`);
    const data = await response.json();
    if (data.items?.some(item => item.accommodationId === propertyId)) break;
    if (i === 19) throw new Error('La propiedad publicada no apareció en Search.');
    await page.waitForTimeout(1000);
  }
  await page.goto(`${web}/search?location=Bogot%C3%A1&pageSize=100`);
  const card = page.getByRole('link').filter({ hasText: title });
  await card.waitFor({ timeout: 30000 });
  const photo = card.getByRole('img', { name: title });
  await photo.scrollIntoViewIfNeeded();
  await page.waitForFunction(img => img.complete && img.naturalWidth > 0, await photo.elementHandle(), { timeout: 30000 });
  console.log(`Propiedad publicada desde la interfaz e indexada con foto y coordenadas persistentes: ${propertyId}`);
  await browser.close();
})().catch(async error => { console.error(error.message); await browser?.close(); process.exitCode = 1; });
