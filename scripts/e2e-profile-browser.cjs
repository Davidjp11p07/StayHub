const { chromium } = require('playwright');
const { randomUUID } = require('crypto');
let browser;
(async () => {
  browser = await chromium.launch({ ...(process.env.STAYHUB_BROWSER_PATH ? { executablePath: process.env.STAYHUB_BROWSER_PATH } : { channel: 'chrome' }), headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, ignoreHTTPSErrors: true });
  const email = `browser-${randomUUID()}@stayhub.test`, password = `Smoke-${randomUUID()}`;
  page.on('pageerror', e => console.log('PAGE_ERROR', e.message));
  const web = process.env.STAYHUB_WEB_URL || 'http://localhost:5173';
  await page.goto(`${web}/register`);
  await page.locator('#register-name').fill('Navegador Prueba');
  await page.locator('#register-email').fill(email);
  await page.locator('#register-role').selectOption('GUEST');
  await page.locator('#register-password').fill(password);
  await page.locator('#register-confirm').fill(password);
  await page.locator('form button[type=submit]').click();
  await page.waitForURL('**/login*', { timeout: 30000 });
  await page.locator('#email').fill(email);
  await page.locator('#password').fill(password);
  await page.locator('form button[type=submit]').click();
  await page.waitForURL(url => !url.pathname.startsWith('/login'), { timeout: 30000 });
  await page.goto(`${web}/profile`);
  await page.getByLabel('Foto JPEG o PNG').setInputFiles({ name:'foto.png', mimeType:'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==','base64') });
  await page.getByRole('button', {name:'Guardar cambios'}).click();
  await page.getByText('Perfil actualizado.').waitFor({timeout:30000});
  await page.locator('header').getByRole('img', {name:'Foto de perfil'}).waitFor({timeout:30000});
  await page.locator('main').getByRole('img', {name:'Foto de perfil'}).waitFor({timeout:30000});
  await page.reload();
  await page.locator('header').getByRole('img', {name:'Foto de perfil'}).waitFor({timeout:30000});
  await page.locator('main').getByRole('img', {name:'Foto de perfil'}).waitFor({timeout:30000});
  console.log('Registro, acceso, carga y visualización persistente de foto: OK');
  await page.screenshot({path:'.artifacts/profile-verified.png'});
  await browser.close();
})().catch(async error => { console.error(error.message); await browser?.close(); process.exitCode=1; });
